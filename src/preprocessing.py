from pathlib import Path
import unicodedata
import re
import pandas as pd
from sklearn.model_selection import train_test_split


PROJECT_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_DATA_PATH = PROJECT_ROOT / "data" / "sms_spam.csv"
DEFAULT_CLEANED_DATA_PATH = PROJECT_ROOT / "data" / "sms_spam_cleaned.csv"
DEFAULT_SYNTHETIC_PATH = PROJECT_ROOT / "data" / "synthetic_data.csv"


def clean_text(text: str) -> str:
    """
    Normalize and clean an SMS text message string.

    Applies:
        - Unicode NFKD normalization
        - Replacement of typographical quotes, dashes, ellipses, currency symbols
        - Collapsing of redundant whitespace
        - Stripping leading and trailing whitespace
    """
    if not isinstance(text, str):
        return ""

    # Unicode NFKD normalization (decomposes combined/fancy characters)
    text = unicodedata.normalize("NFKD", text)

    # Standardize unicode punctuation & symbols to ASCII equivalents
    char_replacements = {
        "\u2018": "'",    # left single curly quote
        "\u2019": "'",    # right single curly quote
        "\u201c": '"',    # left double curly quote
        "\u201d": '"',    # right double curly quote
        "\u2013": "-",    # en dash
        "\u2014": "-",    # em dash
        "\u2026": "...",  # ellipsis
        "\u00a0": " ",    # non-breaking space
        "\u0092": "'",    # Windows-1252 right single quote
        "\u0093": '"',    # Windows-1252 left double quote
        "\u0094": '"',    # Windows-1252 right double quote
        "\u20b9": "Rs ",  # Indian Rupee symbol
    }
    for old, new in char_replacements.items():
        text = text.replace(old, new)

    # Collapse consecutive whitespace characters into a single space
    text = re.sub(r"\s+", " ", text)

    return text.strip()


def clean_dataframe(df: pd.DataFrame, drop_duplicates: bool = True) -> pd.DataFrame:
    """
    Clean and validate a dataset containing 'text' and 'label' columns.

    Steps:
        1. Standardize column names.
        2. Remove missing values.
        3. Clean and normalize text messages.
        4. Normalize labels to lowercase ('ham', 'spam').
        5. Remove empty messages.
        6. Drop duplicate text entries (optional, default True).
        7. Validate that only valid labels exist.
    """
    df = df.copy()

    # Standardize column names
    df.columns = df.columns.astype(str).str.strip().str.lower()

    required_columns = {"text", "label"}
    if not required_columns.issubset(df.columns):
        raise ValueError(
            f"Dataset must contain 'text' and 'label' columns. Found: {df.columns.tolist()}"
        )

    df = df[["text", "label"]]
    df = df.dropna(subset=["text", "label"])

    # Clean text and normalize labels
    df["text"] = df["text"].apply(clean_text)
    df["label"] = df["label"].astype(str).str.strip().str.lower()

    # Remove empty text messages
    df = df[df["text"] != ""]

    # Remove duplicate texts if requested
    if drop_duplicates:
        df = df.drop_duplicates(subset=["text"], keep="first")

    # Validate labels
    invalid_labels = df[~df["label"].isin(["ham", "spam"])]
    if not invalid_labels.empty:
        raise ValueError(
            f"Dataset contains invalid labels: {invalid_labels['label'].unique().tolist()}"
        )

    return df.reset_index(drop=True)


def load_dataset(
    file_path=DEFAULT_DATA_PATH,
    clean: bool = True,
    drop_duplicates: bool = True
) -> pd.DataFrame:
    """
    Load and optionally clean the SMS Spam Collection dataset.

    If file_path is the default path and DEFAULT_CLEANED_DATA_PATH exists,
    it falls back to the cleaned file if the primary path is locked or unavailable.
    """
    file_path = Path(file_path)

    # Use cleaned copy if available and default file is targeted
    target_path = file_path
    if file_path == DEFAULT_DATA_PATH and DEFAULT_CLEANED_DATA_PATH.exists():
        target_path = DEFAULT_CLEANED_DATA_PATH

    if not target_path.exists():
        if file_path.exists():
            target_path = file_path
        else:
            raise FileNotFoundError(f"Dataset not found: {file_path}")

    try:
        df = pd.read_csv(target_path, encoding="utf-8-sig")
    except UnicodeDecodeError:
        df = pd.read_csv(target_path, encoding="latin-1")

    if clean:
        df = clean_dataframe(df, drop_duplicates=drop_duplicates)

    return df


def load_synthetic_dataset(
    file_path=DEFAULT_SYNTHETIC_PATH,
    clean: bool = True,
    drop_duplicates: bool = True
) -> pd.DataFrame:
    """
    Load and validate the synthetic SMS dataset generated by Generative AI.
    """
    file_path = Path(file_path)
    if not file_path.exists():
        raise FileNotFoundError(f"Synthetic dataset not found: {file_path}")

    try:
        df = pd.read_csv(file_path, encoding="utf-8-sig")
    except UnicodeDecodeError:
        df = pd.read_csv(file_path, encoding="latin-1")

    if clean:
        df = clean_dataframe(df, drop_duplicates=drop_duplicates)

    return df


def prepare_data(
    df: pd.DataFrame,
    test_size: float = 0.20,
    real_fraction: float = 0.20,
    random_state: int = 42
):
    """
    Split the dataset into training and testing sets, then restrict the
    available real training portion according to real_fraction.

    Returns:
        X_real (pd.Series): Restricted real training text messages.
        X_test (pd.Series): Held-out test text messages.
        y_real (pd.Series): Restricted real training labels.
        y_test (pd.Series): Held-out test labels.
    """
    if not 0 < test_size < 1:
        raise ValueError("test_size must be between 0 and 1.")

    if not 0 < real_fraction < 1:
        raise ValueError("real_fraction must be between 0 and 1.")

    X = df["text"]
    y = df["label"]

    # Reserve the real test set (stratified to preserve class proportions)
    X_train, X_test, y_train, y_test = train_test_split(
        X,
        y,
        test_size=test_size,
        stratify=y,
        random_state=random_state
    )

    # Restrict the available training portion (limited real data)
    X_real, _, y_real, _ = train_test_split(
        X_train,
        y_train,
        train_size=real_fraction,
        stratify=y_train,
        random_state=random_state
    )

    return (
        X_real.reset_index(drop=True),
        X_test.reset_index(drop=True),
        y_real.reset_index(drop=True),
        y_test.reset_index(drop=True)
    )


def create_synthetic_subsets(
    synthetic_df: pd.DataFrame,
    n_real_ham: int,
    n_real_spam: int,
    fractions=(0.25, 0.50, 1.0),
    random_state: int = 42
) -> dict:
    """
    Generate nested subsets of synthetic data corresponding to proportions
    (e.g., 25%, 50%, 100%) of the real training class counts.

    Returns:
        dict: Mapping fraction labels (e.g., '25%', '50%', '100%') to DataFrames.
    """
    ham_syn = (
        synthetic_df[synthetic_df["label"] == "ham"]
        .sample(frac=1, random_state=random_state)
        .reset_index(drop=True)
    )
    spam_syn = (
        synthetic_df[synthetic_df["label"] == "spam"]
        .sample(frac=1, random_state=random_state)
        .reset_index(drop=True)
    )

    subsets = {}
    for frac in fractions:
        n_h = int(round(n_real_ham * frac))
        n_s = int(round(n_real_spam * frac))

        if n_h > len(ham_syn) or n_s > len(spam_syn):
            raise ValueError(
                f"Requested {n_h} ham / {n_s} spam at fraction {frac}, but only "
                f"{len(ham_syn)} ham / {len(spam_syn)} spam available."
            )

        subset = pd.concat(
            [ham_syn.iloc[:n_h], spam_syn.iloc[:n_s]],
            ignore_index=True
        )
        subsets[f"{int(frac * 100)}%"] = subset

    return subsets


